/**
 * The deep catalogue (game P12-D): Emberwood (T3, ilvl 13–18), Sungraze
 * Savanna (T4, 19–24), Ashcrag Canyons and the Elder Grove (T5, 25–30), the six
 * handcrafted Legendaries, and the consumables and junk the upper bands need.
 *
 * Same contract as `item-data.mjs`, which shipped T1–T2: **numbers are DERIVED,
 * never typed.** Every stat block, damage band and price runs through the shared
 * ITEMS_LOOT §2 formulas — the same ones the panel's budget meter and the game's
 * roller use — so authoring here is choosing identity (name, slot, ilvl, rarity,
 * which attributes, which icon, one line of flavour) and a tuning pass changes a
 * formula rather than two hundred rows.
 *
 * Armour ships as SETS. Five slots with one authored name each is how a set
 * reads in the fiction and in the inventory, and it is the opposite of the
 * procedural naming §8 forbids: "Cinderplate Greaves" is a piece of a thing
 * somebody made, "Legplates of the Bear +2" is a slot machine.
 */

import { itemValue, statBudget, weaponDamageFor } from '@dawned/shared';

const splitStats = (budget, weights) => {
  const total = Object.values(weights).reduce((sum, weight) => sum + weight, 0);
  const keys = Object.keys(weights);
  const stats = {};
  let spent = 0;
  keys.forEach((key, index) => {
    if (index === keys.length - 1) {
      stats[key] = Math.max(1, budget - spent);
      return;
    }
    const share = Math.max(1, Math.round((budget * weights[key]) / total));
    stats[key] = share;
    spent += share;
  });
  return stats;
};

/** Fraction of the budget a droppable piece fixes; the rest is rolled per copy. */
const FIXED_SHARE = 0.55;

const gear = ({
  id,
  name,
  category,
  slot,
  ilvl,
  rarity = 'common',
  icon,
  flavor,
  weights,
  rollPool,
  armorClass = null,
  classLock = [],
  modelRef = null,
  weapon = null,
  effect = null,
  requiresLevel = null,
}) => {
  const budget = statBudget(slot, ilvl, rarity);
  const points = Math.max(1, Math.round(budget * (rollPool ? FIXED_SHARE : 1)));
  const def = {
    id,
    name,
    category,
    slot,
    rarity,
    ilvl,
    classLock,
    stack: 1,
    value: itemValue(category, slot, ilvl, rarity),
    icon,
    modelRef,
    flavor,
    stats: splitStats(points, weights),
    armorClass,
    effect,
    requiresLevel: requiresLevel ?? ilvl,
    bound: false,
  };
  if (rollPool) def.rollPool = rollPool;
  if (weapon) {
    const band = weaponDamageFor(ilvl);
    def.weapon = { dmgMin: band.min, dmgMax: band.max, twoHanded: weapon.twoHanded ?? false };
  }
  return def;
};

const consumable = ({ id, name, ilvl, icon, flavor, consumable: block, rarity = 'common' }) => ({
  id,
  name,
  category: 'consumable',
  slot: 'none',
  rarity,
  ilvl,
  classLock: [],
  stack: 20,
  value: itemValue('consumable', 'none', ilvl, rarity),
  icon,
  modelRef: null,
  flavor,
  stats: {},
  weapon: null,
  armorClass: null,
  effect: null,
  consumable: block,
  requiresLevel: 1,
  bound: false,
});

