const SLOTS = [
  { slot: 'head', suffix: 'Helm', icon: 'helm', weightBias: 0.7 },
  { slot: 'chest', suffix: 'Chestguard', icon: 'chest', weightBias: 1 },
  { slot: 'legs', suffix: 'Greaves', icon: 'legs', weightBias: 0.85 },
  { slot: 'boots', suffix: 'Boots', icon: 'boots', weightBias: 0.6 },
  { slot: 'gloves', suffix: 'Gloves', icon: 'gloves', weightBias: 0.6 },
];

/**
 * @param set { id, name, ilvl, rarity, armorClass, weights, rollPool, flavor, icons, slots? }
 * `icons` is keyed by the SLOTS icon key; every piece needs its own, because
 * publish refuses a duplicate icon anywhere in the catalogue.
 */
const armorSet = (set) =>
  SLOTS.filter((entry) => (set.slots ?? SLOTS.map((s) => s.icon)).includes(entry.icon)).map(
    (entry) =>
      gear({
        id: `item_armor_${entry.slot}_${set.id}`,
        name: `${set.name} ${entry.suffix}`,
        category: 'armor',
        slot: entry.slot,
        ilvl: set.ilvl,
        rarity: set.rarity ?? 'common',
        icon: set.icons[entry.icon],
        flavor: set.flavor[entry.icon],
        armorClass: set.armorClass,
        weights: set.weights,
        rollPool: set.rollPool,
      }),
  );

